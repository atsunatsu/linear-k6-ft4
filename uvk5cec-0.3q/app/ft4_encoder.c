/*
 * FT4 Encoder - Proper implementation based on WSJT-X ft8_lib
 * Reference: https://github.com/kgoba/ft8_lib
 *
 * FT4 encoding flow:
 * 1. XOR 77-bit message with pseudorandom sequence
 * 2. Compute CRC-14 and append to get 91 bits
 * 3. LDPC(174,91) encode 91 bits -> 174 bits
 * 4. Gray mapping: 2 bits -> 1 symbol (0-3)
 * 5. Insert sync patterns and ramp symbols
 *
 * Frame: R + S4 + D29 + S4 + D29 + S4 + D29 + S4 + R = 105 symbols
 */

