static uint8_t parity8(uint8_t x)
{
    x ^= x >> 4;
    x ^= x >> 2;
    x ^= x >> 1;
    return x & 1;
}

static uint16_t compute_crc(const uint8_t *msg, int num_bits)
{
    uint16_t rem = 0;
    int ibyte = 0, ibit;
    const uint16_t top = 1u << (FT8_CRC_WIDTH - 1);
    for (ibit = 0; ibit < num_bits; ++ibit) {
        if (ibit % 8 == 0) {
            rem ^= (msg[ibyte] << (FT8_CRC_WIDTH - 8));
            ++ibyte;
        }
        rem = (rem & top) ? ((rem << 1) ^ FT8_CRC_POLY) : (rem << 1);
    }
    return rem & ((top << 1) - 1u);
}

static void add_crc(const uint8_t *payload, uint8_t *a91)
{
    int i;
    for (i = 0; i < 10; i++) a91[i] = payload[i];
    a91[9] &= 0xF8u;
    a91[10] = 0;
    uint16_t crc = compute_crc(a91, 96 - 14);
    a91[9]  |= (uint8_t)(crc >> 11);
    a91[10]  = (uint8_t)(crc >> 3);
    a91[11]  = (uint8_t)(crc << 5);
}

static void ldpc_encode(const uint8_t *msg, uint8_t *cw)
{
    int i, j;
    uint8_t mask, idx;
    for (j = 0; j < FTX_LDPC_N_BYTES; ++j)
        cw[j] = (j < FTX_LDPC_K_BYTES) ? msg[j] : 0;
    mask = 0x80u >> (FTX_LDPC_K % 8u);
    idx = FTX_LDPC_K_BYTES - 1;
    for (i = 0; i < FTX_LDPC_M; ++i) {
        uint8_t s = 0;
        for (j = 0; j < FTX_LDPC_K_BYTES; ++j)
            s ^= parity8(msg[j] & kLDPC_G[i][j]);
        if (s & 1) cw[idx] |= mask;
        mask >>= 1;
        if (mask == 0) { mask = 0x80u; ++idx; }
    }
}

void FT4ENC_Init(void) { }

int FT4ENC_EncodeMessage(const uint8_t *payload77, uint8_t *tones)
{
    uint8_t px[10], a91[FTX_LDPC_K_BYTES], cw[FTX_LDPC_N_BYTES];
    int i;
    uint8_t mask, ib, b2;

    if (!payload77 || !tones) return -1;

    for (i = 0; i < 10; ++i) px[i] = payload77[i] ^ kFT4_XOR_seq[i];
    add_crc(px, a91);
    ldpc_encode(a91, cw);

    mask = 0x80u; ib = 0;
    for (i = 0; i < FT4_NN; ++i) {
        if (i == 0 || i == 104)        { tones[i] = 0; }
        else if (i >= 1   && i < 5)    { tones[i] = kFT4_Costas[0][i-1]; }
        else if (i >= 34  && i < 38)   { tones[i] = kFT4_Costas[1][i-34]; }
        else if (i >= 67  && i < 71)   { tones[i] = kFT4_Costas[2][i-67]; }
        else if (i >= 100 && i < 104)  { tones[i] = kFT4_Costas[3][i-100]; }
        else {
            b2 = 0;
            if (cw[ib] & mask) b2 |= 2;
            mask >>= 1; if (!mask) { mask = 0x80u; ib++; }
            if (cw[ib] & mask) b2 |= 1;
            mask >>= 1; if (!mask) { mask = 0x80u; ib++; }
            tones[i] = kFT4_Gray[b2];
        }
    }
    return FT4_NN;
}
